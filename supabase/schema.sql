-- Guestbook table schema & Row Level Security (RLS) policies for Supabase
-- Run this in your Supabase Dashboard -> SQL Editor

create table if not exists public.guestbook (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(trim(name)) between 1 and 80),
  message text not null check (char_length(trim(message)) between 1 and 1000),
  created_at timestamptz not null default now()
);

-- Index for fast reverse-chronological queries
create index if not exists guestbook_created_at_idx
  on public.guestbook (created_at desc);

-- Enable Row Level Security
alter table public.guestbook enable row level security;

-- Allow public read access (needed if using the anon key on the backend)
drop policy if exists "Allow public guestbook reads" on public.guestbook;
create policy "Allow public guestbook reads"
  on public.guestbook
  for select
  to anon, authenticated
  using (true);

-- Allow public insert access (needed if using the anon key on the backend)
drop policy if exists "Allow public guestbook inserts" on public.guestbook;
create policy "Allow public guestbook inserts"
  on public.guestbook
  for insert
  to anon, authenticated
  with check (
    char_length(trim(name)) between 1 and 80
    and char_length(trim(message)) between 1 and 1000
  );
